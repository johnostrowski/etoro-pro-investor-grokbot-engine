#!/usr/bin/env python3
"""Sum the content calendar's hours and write tiers.md next to the registry.

Reads content-types.toml (the registry). Standard library only, so it runs anywhere with
Python 3.11 or later.

    python3 tools/content_strategy/build.py            # write tiers.md
    python3 tools/content_strategy/build.py --check    # fail if tiers.md is stale or a tier is over its cap
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# The registry sits in docs/content-strategy/ in the private working system and in content/ in the
# exported engine. The same script serves both.
BASE = next(
    (d for d in (ROOT / "docs" / "content-strategy", ROOT / "content") if (d / "content-types.toml").exists()),
    ROOT / "content",
)
REGISTRY = BASE / "content-types.toml"
OUTPUT = BASE / "tiers.md"

WEEKS_PER_MONTH = 52 / 12
TIER_ORDER = ["starter", "core", "full"]
LAYER_ORDER = ["promise", "series", "reactive", "campaign", "habit", "evergreen", "ops"]
PILLARS = ["educational", "performance", "engagement", "promotional"]
PILLAR_TARGET = {"educational": 40, "performance": 30, "engagement": 20, "promotional": 10}
# Layers that produce a published piece. Habits and operations take time but are not posts.
PIECE_LAYERS = {"promise", "series", "reactive", "campaign", "evergreen"}


def load() -> dict:
    with REGISTRY.open("rb") as handle:
        return tomllib.load(handle)


def slot_for(kind: dict, tier: str) -> dict | None:
    """The {per_month, minutes} a type has in a tier, or None when it is not in that tier."""
    if kind["status"] != "active":
        return None
    return kind.get("tiers", {}).get(tier)


def hours_per_week(minutes_per_month: float) -> float:
    return minutes_per_month / WEEKS_PER_MONTH / 60


def frequency(per_month: float) -> str:
    if per_month >= 12:
        return f"{round(per_month / WEEKS_PER_MONTH)} a week"
    if per_month >= 8:
        return "2 a week"
    if per_month >= 4:
        return "weekly" if per_month < 5 else f"{per_month:g} a month"
    if 2 < per_month < 2.5:
        return "every 2 weeks"
    if per_month >= 1 and per_month == int(per_month):
        return "monthly" if per_month == 1 else f"{per_month:g} a month"
    per_year = round(per_month * 12)
    return {1: "yearly", 4: "quarterly"}.get(per_year, f"{per_year} a year")


def tier_minutes(types: list[dict], tier: str) -> float:
    return sum(s["per_month"] * s["minutes"] for k in types if (s := slot_for(k, tier)))


def pillar_mix(types: list[dict], tier: str) -> dict[str, float]:
    counts = {p: 0.0 for p in PILLARS}
    for kind in types:
        slot = slot_for(kind, tier)
        if slot and kind["layer"] in PIECE_LAYERS and kind["pillar"] in counts:
            counts[kind["pillar"]] += slot["per_month"]
    total = sum(counts.values()) or 1
    return {p: 100 * n / total for p, n in counts.items()}


def render(data: dict) -> str:
    types = data["types"]
    engine = [k for k in types if k["scope"] == "engine"]
    lines = [
        "# Tiers — hours and types",
        "",
        "<!-- Generated by tools/content_strategy/build.py from content-types.toml. Do not edit by hand. -->",
        "",
        f"Registry version {data['version']}, updated {data['updated']}. Minutes are the owner's own time per",
        "piece (review, record, post, reply). They are estimates until the Monday log has a quarter of actuals.",
        "",
        "## Hours a week",
        "",
        "| Tier | Estimated | Cap | Pieces a month | What it is |",
        "|---|---|---|---|---|",
    ]
    over_cap = []
    for tier in TIER_ORDER:
        meta = data["tiers"][tier]
        hours = hours_per_week(tier_minutes(engine, tier))
        pieces = sum(
            s["per_month"] for k in engine if (s := slot_for(k, tier)) and k["layer"] in PIECE_LAYERS
        )
        if hours > meta["cap_hours_per_week"]:
            over_cap.append(tier)
        lines.append(
            f"| **{meta['label']}** | {hours:.1f} h | {meta['cap_hours_per_week']} h | {pieces:.0f} | {meta['promise']} |"
        )

    for name, profile in data.get("profiles", {}).items():
        base_minutes = tier_minutes(engine, profile["base"])
        extra = [k for k in types if k["id"] in profile["add"] and k["status"] == "active"]
        extra_minutes = sum(k["instance"]["per_month"] * k["instance"]["minutes"] for k in extra)
        total = hours_per_week(base_minutes + extra_minutes)
        low, high = profile["budget_hours_per_week"]
        if total > high:
            over_cap.append(name)
        lines += [
            "",
            f"**{profile['label']}** runs {data['tiers'][profile['base']]['label']} "
            f"({hours_per_week(base_minutes):.1f} h) plus the instance types "
            f"({hours_per_week(extra_minutes):.1f} h): **{total:.1f} h a week** against a budget of {low} to {high} h.",
        ]

    lines += ["", "## Types by tier", "", "| Layer | Type | Slot | Starter | Core | Full | Min each |", "|---|---|---|---|---|---|---|"]
    for layer in LAYER_ORDER:
        for kind in (k for k in engine if k["layer"] == layer and k["status"] == "active"):
            cells = []
            for tier in TIER_ORDER:
                slot = slot_for(kind, tier)
                cells.append(frequency(slot["per_month"]) if slot else "—")
            minutes = sorted({s["minutes"] for s in kind["tiers"].values()})
            lines.append(
                f"| {layer.capitalize()} | **{kind['name']}** | {kind['slot']} | "
                + " | ".join(cells)
                + f" | {'–'.join(str(m) for m in minutes)} |"
            )

    lines += ["", "## Pillar mix, by pieces a month", "", "| Tier | Educational | Performance | Engagement | Promotional |", "|---|---|---|---|---|"]
    lines.append("| *Default target* | " + " | ".join(f"{PILLAR_TARGET[p]}%" for p in PILLARS) + " |")
    for tier in TIER_ORDER:
        mix = pillar_mix(engine, tier)
        lines.append(f"| {data['tiers'][tier]['label']} | " + " | ".join(f"{mix[p]:.0f}%" for p in PILLARS) + " |")
    lines += [
        "",
        "Reply sessions are engagement work but not pieces, so they are not in this table. The promotional",
        "share stays near zero while the copy invite is gated (see the strategy, *Open decisions*).",
    ]

    lines += ["", "## Who owns each type", "", "| Type | Owner (first level) | Fuel from | Bar raiser (second level) |", "|---|---|---|---|"]
    for kind in (k for k in types if k["status"] == "active"):
        raiser = "—" if kind["bar_raiser"] == "none" else f"`{kind['bar_raiser']}`"
        lines.append(f"| {kind['name']} | {kind['owner']} | {kind['fuel']} | {raiser} |")

    idle = [k for k in engine if k["status"] != "active"]
    if idle:
        lines += ["", "## Listed, not counted", "", "| Type | Status | Why |", "|---|---|---|"]
        reasons = {
            "paused": "Paused in v1. No hours are planned for it.",
            "gated": "Waits on a compliance answer. No hours are planned for it.",
        }
        for kind in idle:
            lines.append(f"| {kind['name']} | {kind['status']} | {reasons.get(kind['status'], '')} |")

    instance = [k for k in types if k["scope"] == "instance"]
    if instance:
        lines += ["", "## Instance types (this owner only)", "", "| Brand | Type | Slot | Frequency | Min each |", "|---|---|---|---|---|"]
        for kind in instance:
            slot = kind["instance"]
            lines.append(
                f"| {kind['brand'].capitalize()} | **{kind['name']}** | {kind['slot']} | "
                f"{frequency(slot['per_month'])} | {slot['minutes']} |"
            )

    text = "\n".join(lines) + "\n"
    return text, over_cap


def main() -> int:
    text, over_cap = render(load())
    if "--check" in sys.argv:
        problems = [f"{name} is over its hours cap" for name in over_cap]
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            problems.append("tiers.md is stale: run tools/content_strategy/build.py")
        for problem in problems:
            print(f"FAIL: {problem}")
        return 1 if problems else 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    for name in over_cap:
        print(f"WARNING: {name} is over its hours cap")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
